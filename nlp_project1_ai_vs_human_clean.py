class LinguisticFeatures(BaseEstimator, TransformerMixin):
    # Six deterministic linguistic features from the original ML project.
    def fit(self, X, y=None):
        return self

    def transform(self, X):
        if isinstance(X, pd.DataFrame):
            texts = X.iloc[:, 0].tolist()
        elif isinstance(X, pd.Series):
            texts = X.tolist()
        else:
            texts = np.asarray(X).reshape(-1).tolist()

        values = []
        pronouns = {'i', 'we', 'my', 'our', 'us', 'their'}
        for t in texts:
            text = str(t)
            words = text.split()
            n = max(1, len(words))
            sentences = [s.strip() for s in re.split(r'[.!?]', text) if s.strip()]
            ns = len(sentences)
            values.append([
                len(words) / ns if ns else 0.0,
                len(set(words)) / n,
                sum(ch in '.,;:!?' for ch in text) / n,
                sum(len(w) > 1 and w[0].isupper() for w in words) / n,
                sum(w.lower() in pronouns for w in words) / n,
                float(ns)
            ])
        return np.asarray(values, dtype=float)


def make_model(name, *, remove_stop_words=False, add_manual_features=False):
    models = {
        'Naive Bayes': lambda: MultinomialNB(),
        'Logistic Regression': lambda: LogisticRegression(max_iter=2000, random_state=RANDOM_STATE),
        'SVM': lambda: LinearSVC(max_iter=10000, random_state=RANDOM_STATE),
    }
    if name not in models:
        raise ValueError(f'Unknown model: {name}')
    steps = [
        ('tfidf', TfidfVectorizer(max_features=MAX_FEATURES,
                                  ngram_range=(1, 2),
                                  stop_words='english' if remove_stop_words else None), 'Text')
    ]
    if add_manual_features:
        steps.append(('manual', Pipeline([
            ('extract', LinguisticFeatures()),
            ('scale', StandardScaler())
        ]), 'Text'))
    features = ColumnTransformer(steps)
    return Pipeline([('features', features), ('classifier', models[name]())])

cv = StratifiedGroupKFold(n_splits=CV_FOLDS, shuffle=True, random_state=RANDOM_STATE)

def evaluate_cv(model):
    scores = cross_validate(model, X_train, y_train, cv=cv,
                            groups=training_groups,
                            scoring={'accuracy':'accuracy', 'f1_macro':'f1_macro'},
                            n_jobs=1, error_score='raise')
    return {
        'CV Accuracy': scores['test_accuracy'].mean(),
        'CV F1 (macro)': scores['test_f1_macro'].mean(),
        'CV F1 std': scores['test_f1_macro'].std(),
    }

